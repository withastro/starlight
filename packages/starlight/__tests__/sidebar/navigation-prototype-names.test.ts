import { describe, expect, test, vi } from 'vitest';
import { getSidebar } from '../../src/utils/navigation';

vi.mock('astro:content', async () =>
	(await import('../test-utils')).mockedAstroContent({
		docs: [
			['index.mdx', { title: 'Home Page' }],
			['resources/plugins.mdx', { title: 'Plugins' }],
			['resources/themes.mdx', { title: 'Themes' }],
			['reference/constructor/overview.md', { title: 'Constructor API' }],
			['reference/toString/overview.md', { title: 'toString API' }],
			['reference/hasOwnProperty/overview.md', { title: 'hasOwnProperty API' }],
			['reference/ordinary/overview.md', { title: 'Ordinary API' }],
		],
	})
);

describe('getSidebar', () => {
	test('includes autogenerated directories named like Object.prototype properties', () => {
		const sidebar = getSidebar('/reference/constructor/overview/', undefined);
		const reference = sidebar.find((entry) => entry.label === 'Reference');
		const groups = reference?.type === 'group' ? reference.entries : [];
		expect(groups.map((entry) => entry.label)).toEqual([
			'constructor',
			'hasOwnProperty',
			'ordinary',
			'toString',
		]);
		const constructorGroup = groups.find((entry) => entry.label === 'constructor');
		expect(constructorGroup?.type === 'group' && constructorGroup.entries[0]).toMatchObject({
			label: 'Constructor API',
			isCurrent: true,
		});
	});
});
